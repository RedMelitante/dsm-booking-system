// Prints SQL that (re)creates the three fictional demo businesses from the
// design handoff (src/data/demo-businesses.json), owned by a "demo owner" with
// no password, so /lumen-skin-studio, /brightside-dental and /snapshot-booth-co
// work as live demo booking pages.
//
// migrations/0002_demo_businesses.sql was generated with this script and is
// applied automatically. Re-run it to reset the demos:
//   node scripts/seed-demo.mjs > .wrangler/seed.sql
//   npx wrangler d1 execute dsm-booking --local --file=.wrangler/seed.sql   (or --remote)
import fs from 'node:fs';

const data = JSON.parse(fs.readFileSync(new URL('../src/data/demo-businesses.json', import.meta.url), 'utf8'));
const q = (v) => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : "'" + String(v).replace(/'/g, "''") + "'");
const key = (label) => (/^packages?$/i.test(label) ? 'pkg' : label.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, ''));
const DOW = { Sunday: 0, Monday: 1, Tuesday: 2, Wednesday: 3, Thursday: 4, Friday: 5, Saturday: 6 };
const now = Number(process.env.SEED_TIME) || Date.now();
const OWNER = 'demo-owner';

const out = ['-- Demo businesses from the design handoff (generated by scripts/seed-demo.mjs).'];
out.push(`DELETE FROM services WHERE business_id IN (SELECT id FROM businesses WHERE owner_id = '${OWNER}');`);
out.push(`DELETE FROM staff WHERE business_id IN (SELECT id FROM businesses WHERE owner_id = '${OWNER}');`);
out.push(`DELETE FROM hours WHERE business_id IN (SELECT id FROM businesses WHERE owner_id = '${OWNER}');`);
out.push(`DELETE FROM businesses WHERE owner_id = '${OWNER}';`);
out.push(`INSERT OR IGNORE INTO users (id, email, name, password_hash, created_at) VALUES ('${OWNER}', 'demo-owner@example.invalid', 'Demo owner', NULL, ${now});`);

const TEMPLATE = { 'salons-wellness': 'salon', 'clinics-medical': 'clinic', 'events-rentals': 'events' };

for (const b of data.businesses) {
  const id = 'demo-' + b.slug;
  const labels = b.labels || {};
  const svcNoun = labels.service || 'service';
  const staffNoun = labels.staff || 'Staff member';
  const cats = [['all', 'All']].concat((b.categories || []).map((c) => [key(c), c]));
  const settings = {
    interval: (b.hours && b.hours.slotInterval) || 30, notice: 2, advance: 60, approval: false, staffStep: true, prices: true,
    notify: { newBooking: false, confirmation: true, changes: true, digest: false, followUp: false, remind: 'off' },
    ownerEmail: '', fromName: b.name,
  };
  const staffSub = {
    salon: 'Pick someone you know, or let the studio match you with whoever is free first.',
    clinic: 'Returning patients can keep their usual dentist. New patients can take the earliest slot.',
    events: 'Each booth has a different look. Pick one, or take whichever is free on your date.',
  }[TEMPLATE[b.template]] || 'Pick someone, or take whoever is free first.';
  out.push(`INSERT INTO businesses (id, owner_id, slug, name, website, template, currency, timezone, accent, kind, place, svc_noun, staff_noun, any_name, any_role, staff_sub, policy, deposit_pct, categories, settings, created_at) VALUES (${[
    id, OWNER, b.slug, b.name, '', TEMPLATE[b.template] || 'blank', b.currency, b.timezone, b.accent, b.kind, b.place, svcNoun, staffNoun,
    labels.anyStaff || 'Anyone available', 'Most availability', staffSub, b.policy || '', (b.depositPercent || 0) / 100,
    JSON.stringify(cats), JSON.stringify(settings), now,
  ].map(q).join(', ')});`);

  const closed = (b.hours.closedDays || []).map((d) => DOW[d]);
  for (let dow = 0; dow < 7; dow++) {
    const close = dow === 6 && b.hours.saturdayClose ? b.hours.saturdayClose : b.hours.close;
    out.push(`INSERT INTO hours (business_id, dow, is_open, open_min, close_min) VALUES (${q(id)}, ${dow}, ${closed.includes(dow) ? 0 : 1}, ${b.hours.open}, ${close});`);
  }
  (b.staff || []).forEach((s, i) => {
    out.push(`INSERT INTO staff (id, business_id, name, role, color, sort) VALUES (${[id + '-' + s.id, id, s.name, s.role || '', s.color || '#5B4BDB', i].map(q).join(', ')});`);
  });
  const questions = (b.questions || []).map((x) => ({
    id: x.id, label: x.label, type: x.type === 'choice' ? 'select' : x.type, req: !!x.required, options: x.options || [],
  }));
  (b.services || []).forEach((s, i) => {
    const pkg = s.type === 'package' || key(s.category || '') === 'pkg';
    out.push(`INSERT INTO services (id, business_id, name, category, duration, price, from_price, buffer, description, active, is_package, badge, meta, includes, addons, questions, staff_ids, sort, created_at) VALUES (${[
      id + '-' + s.id, id, s.name, pkg ? 'pkg' : key(s.category || ''), s.durationMin, s.price || 0, s.fromPrice || s.priceFrom ? 1 : 0, 0,
      s.description || '', 1, pkg ? 1 : 0, s.badge || '', s.durationLabel || '', JSON.stringify(s.includes || []),
      JSON.stringify((s.addons || []).map((a) => ({ id: a.id, name: a.name, price: a.price }))), JSON.stringify(questions), '[]', i, now + i,
    ].map(q).join(', ')});`);
  });
}
process.stdout.write(out.join('\n') + '\n');
